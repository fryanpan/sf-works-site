export const METRE = 1609.344;

// Two significant figures everywhere a figure is derived rather than counted.
// Bryan, 2026-09-20: "stick to 2 significant digits throughout. 3 is overkill."
// A third digit on a mileage computed from a traced map with 6.2 m of
// registration error is precision the measurement does not have.
//
// Counts are not rounded: 111 segments is 111, not 110.
export const sig2 = (n) => {
  if (!isFinite(n)) return String(n);
  if (n === 0) return "0";
  const s = Number(n.toPrecision(2));
  return String(s);
};
export const miles = (m) => sig2(m / METRE);
export const pct = (n, d) => sig2((100 * n) / d);

export { esc };

// "ANNAPOLIS TER to TAMALPAIS TER (2400 - 2499)" is how Public Works writes a
// block. Title-case it and drop the address range, which no reader needs to
// picture the segment.
export const block = (limits) =>
  limits
    ? esc(
        limits
          .replace(/\s*\(.*\)\s*$/, "")
          .toLowerCase()
          .replace(/\b[a-z]/g, (c) => c.toUpperCase())
          .replace(/\bTo\b/, "to")
          .replace(/\b0+(\d+)(st|nd|rd|th)\b/gi, "$1$2"),
      )
    : "—";

export const street = (s) =>
  esc(s.toLowerCase().replace(/\b[a-z]/g, (c) => c.toUpperCase()).replace(/\b0+(\d+)(st|nd|rd|th)\b/gi, "$1$2"));


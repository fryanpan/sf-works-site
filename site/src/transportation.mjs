// ---- The two orderings ----------------------------------------------------
//
// Both run worst to best, so a cross-tab of them has a meaning: the diagonal is
// where the city built what it drew, and everything below it is a shortfall.
//
// BUILT is a ladder because the facilities are one: a sharrow is paint that
// says share the lane, a painted lane is paint that separates it, a separated
// lane puts something physical between the bike and the car. A segment carrying
// two is ranked by the better of them.
export const BUILT = ["Nothing", "Sharrow", "Painted lane", "Separated lane"];
// A path ranks with a separated lane: both put something physical between a
// rider and a car, and collect-transportation.mjs counts Class I as meeting a
// Separated block (pipeline review finding 8).
const RANK = { sharrow: 1, "painted lane": 2, "separated lane": 3, path: 3 };
export const builtRank = (s) => Math.max(0, ...s.has.map((h) => RANK[h] ?? 0));

// PLANNED runs worst to best by the plan's own account of its classes, with
// one row that is not on the scale at all.
//
// Separated is the strongest: "vertical separation between people biking and
// rolling and cars. All of these facilities are considered All Ages and
// Abilities" (printed pp. 74–75).
//
// Within Shared, the plan's numbering counts DOWN in quality, which is the
// opposite of how a reader expects levels to run. Level I is Slow Streets
// meeting "low motor vehicle speed + volume thresholds"; Level II has
// "somewhat higher" thresholds and "lower infrastructure investment"; Level
// III is "traffic-calmed streets that manage motor vehicle speed not volume"
// (printed pp. 76–77). I and II each call themselves all-ages-and-abilities in
// their own sentence and III does not, and the North Star map legend treats
// III as a ceiling — lighter shading means nothing "above a Shared Street
// Level III" is likely there "due to street space and geography" (pp. 68–69).
// So Shared L3 ranks below the segments the plan marks Shared without a level.
//
// Undecided is not on the scale, and since 2026-09-20 it is not on the page's
// figures either. The plan draws those streets as part of the network and
// declines to say what to build, so nothing on them can have met or missed it.
// Bryan's call: take them out of the count rather than let one number mean both
// "the plan named a facility nobody built" and "the plan named none". They are
// reported on their own, from `data.undecided`.
export const PLANNED = ["Shared L3", "Shared", "Separated"];

/** The segments the page counts. The Undecided 15 are not among them. */
export const scored = data.segments.filter((s) => s.status !== "unrated");

/** The Undecided segments, which carry what is built but no verdict. */
export const unrated = data.segments.filter((s) => s.status === "unrated");

/** The cross-tab, as `grid[planned][builtRank] = {segments, metres}`. */
export function crossTab() {
  const grid = {};
  for (const p of PLANNED) grid[p] = BUILT.map(() => ({ segments: 0, metres: 0 }));
  for (const s of scored) {
    const cell = grid[s.wants]?.[builtRank(s)];
    if (!cell) continue;
    cell.segments += 1;
    cell.metres += s.lengthM;
  }
  return grid;
}

/** Metres on the plan's network, split by whether the paving delivered it. */
export function milesByStatus() {
  const out = { meets: 0, short: 0, none: 0, total: 0 };
  for (const s of scored) {
    out[s.status] += s.lengthM;
    out.total += s.lengthM;
  }
  return out;
}

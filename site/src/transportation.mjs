// Everything the four streets pages share: the data, the units, and the two
// orderings that make the whole tool legible.
//
// The tool answers one question — of the paving done since the Biking and
// Rolling Plan was adopted, how much of it delivered what the plan draws — and
// it answers it in miles. Segment is Public Works' unit, not a reader's: the
// 111 on-plan segments run from 21 m to 340 m, so counting them weights a
// short block the same as a long one.

